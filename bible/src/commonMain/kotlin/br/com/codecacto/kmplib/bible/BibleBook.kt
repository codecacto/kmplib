/** Antigo ou Novo Testamento. */
enum class Testament { OLD, NEW }

/** Nome por extenso e abreviação de um livro num idioma. */
data class BibleBookName(val name: String, val abbreviation: String)

/**
 * Idiomas em que a lib conhece os nomes dos livros (o alcance GLOBAL da fábrica). Não confundir com a
 * TRADUÇÃO embarcada: o pt-PT pode usar o texto pt-BR e mostrar os nomes de Portugal.
 */
enum class BibleLanguage(val tag: String) {
    PT_BR("pt-BR"), PT_PT("pt-PT"), EN("en"), ES("es");

    companion object {
        /**
         * O idioma para a etiqueta BCP-47 (`"pt-BR"`, `"pt_PT"`, `"en-US"`, `"es-419"`). Português sem
         * região, ou de outra região, cai no pt-BR (a mesma escolha de pasta do compose-resources);
         * idioma desconhecido cai no [default].
         */
        fun fromTag(tag: String?, default: BibleLanguage = PT_BR): BibleLanguage {
            val parts = tag.orEmpty().trim().replace('_', '-').lowercase().split('-')
            return when (parts.firstOrNull()) {
                "pt" -> if (parts.getOrNull(1) == "pt") PT_PT else PT_BR
                "en" -> EN
                "es" -> ES
                else -> default
            }
        }
    }
}

